#!/bin/bash
# TURN server (coturn) for Liquidity's Eaglercraft shared worlds.
# When two players can't connect directly (WebRTC), game traffic is relayed through this server.
#   Run on the Hetzner server as root:  bash turn_setup.sh
# Needs Hetzner firewall rules (inbound, Any IPv4): UDP 3478, TCP 3478, UDP 49160-49200.
# Prints the value for Appliku env var LIQUIDITY_EAGLER_ICE_SERVERS.
set -euo pipefail
[ "$(id -u)" = 0 ] || { echo "Run as root."; exit 1; }

PUBIP=$(ip -4 route get 1.1.1.1 | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}')
CONF=/etc/turnserver.conf
SECRET_FILE=/etc/liquidity-turn.pass

if ! command -v turnserver >/dev/null; then
  apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq coturn
fi

umask 077
[ -s "$SECRET_FILE" ] || openssl rand -hex 16 > "$SECRET_FILE"
PASS=$(cat "$SECRET_FILE")

[ -f "$CONF.orig" ] || { [ -f "$CONF" ] && cp "$CONF" "$CONF.orig" || true; }
cat > "$CONF" <<CFG
# Liquidity TURN server (generated by turn_setup.sh)
listening-port=3478
listening-ip=$PUBIP
relay-ip=$PUBIP
external-ip=$PUBIP
min-port=49160
max-port=49200
realm=liquidity
lt-cred-mech
user=liquidity:$PASS
fingerprint
no-tls
no-dtls
no-cli
no-multicast-peers
no-tcp-relay
total-quota=40
user-quota=20
stale-nonce=600
# Never relay into private / local networks (protects the server and Docker).
denied-peer-ip=0.0.0.0-0.255.255.255
denied-peer-ip=10.0.0.0-10.255.255.255
denied-peer-ip=100.64.0.0-100.127.255.255
denied-peer-ip=127.0.0.0-127.255.255.255
denied-peer-ip=169.254.0.0-169.254.255.255
denied-peer-ip=172.16.0.0-172.31.255.255
denied-peer-ip=192.168.0.0-192.168.255.255
denied-peer-ip=224.0.0.0-255.255.255.255
log-file=syslog
CFG
chmod 644 "$CONF"  # readable by the coturn service; the password is shared with game clients anyway

[ -f /etc/default/coturn ] && sed -i 's/^#\?TURNSERVER_ENABLED=.*/TURNSERVER_ENABLED=1/' /etc/default/coturn
if command -v ufw >/dev/null && ufw status | grep -q 'Status: active'; then
  ufw allow 3478/udp >/dev/null; ufw allow 3478/tcp >/dev/null; ufw allow 49160:49200/udp >/dev/null
fi
systemctl enable coturn >/dev/null 2>&1 || true
systemctl restart coturn
sleep 2
systemctl is-active --quiet coturn && echo "==> coturn is running on $PUBIP:3478" || { echo "coturn failed to start:"; journalctl -u coturn -n 30 --no-pager; exit 1; }

echo
echo "In Appliku -> liquidity -> Environment Variables, set this (one line), then Deploy Now:"
echo
echo "LIQUIDITY_EAGLER_ICE_SERVERS"
printf '[{"url":"stun:%s:3478"},{"url":"stun:stun.l.google.com:19302"},{"url":"turn:%s:3478?transport=udp","username":"liquidity","credential":"%s"},{"url":"turn:%s:3478?transport=tcp","username":"liquidity","credential":"%s"}]\n' "$PUBIP" "$PUBIP" "$PASS" "$PUBIP" "$PASS"
